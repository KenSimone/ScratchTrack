// Base class for items in the account tree
class AccountTreeItem
{
public:
	enum accountItemType
	{
		ACCOUNT, // Holds funds
		GROUP, // Display-only method for dividing envelopes
		ENVELOPE // A virtual account, essentially
	}; // enum accountItemType

	AccountTreeItem(accountItemType type);

	static std::vector<AccountTreeItem*> getAllAccountsOfType(accountItemType type);
	virtual AccountTreeItem* getParent() { return nullptr; }

	// TODO: Proper cleanup. Right now we leak items on exit. No one cares.
	virtual ~AccountTreeItem() {};

	// Each item in the tree has a unique ID throughout the system
	// This is used to associate Transactions to categories
	unsigned int getId() { return _id; }

	// This is autogenerated by the constructor. THe only time to call this is deserialization
	void setId(unsigned int id);

	// Look up item by ID
	static AccountTreeItem* lookupById(unsigned int id);

	// The item-type (account/group/envelope)
	virtual accountItemType getType() { return _type; }

	// User-defined name for this item
	virtual const wchar_t* getName() { return _name.c_str(); }
	virtual void setName(const wchar_t* szName) { _name = szName; }

	// Code generated name (can include balance info)
	virtual const wchar_t* getDisplayName() { return getName(); }

	// How many dollars an item has or is holding. Th is is a direct
	// value for accounts and envelopes, and is a calculated value for groups
	virtual int getBalance() { return _balance; }
	virtual void addBalance(int balance) { _balance += balance; }

	// The dollars budgeted to this item. This is a direct value for envelopes
	// and a calculated value for containers.
	virtual int getBudgeted() { return _budgeted; }
	virtual void setBudgeted(int budgeted) { _budgeted = budgeted; }

	// Transaction for self and sub accounts
	int getCurrentMonthTransacationTotal();

	virtual void addChild(AccountTreeItem*) { };
	virtual void addChild(AccountTreeItem*, AccountTreeItem*) {}
	virtual bool removeChild(AccountTreeItem*) { return false; }
	virtual void getIdsForSelfAndChildren(std::set<unsigned int>& ids)
	{
		ids.insert(getId());
	}

	virtual int budgetedToSubAccounts() { return 0; }
	virtual int allocatedToSubAccounts() { return 0; }

	virtual bool isMyChild(unsigned int childId) { return false; }


	// Subclasses should always call base first thing and then add to ppSerializedElement as needed
	virtual int serialize(tinyxml2::XMLElement* pParent, tinyxml2::XMLElement** ppSerializedElement);
	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);

protected:
	accountItemType _type;
	std::wstring _name;
	int _balance;
	int _budgeted;
	unsigned int _id;
};

// Group / folder class and implementation
class AccountGroup : public AccountTreeItem
{
public:
	AccountGroup() : AccountTreeItem(GROUP), _displayName{ 0 } {};
	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);


	// Groups only have aggregate balances from their children and hold no value on their own
	virtual int getBalance() { return 0; }
	virtual void addBalance(int balance) { _balance = 0; }

	virtual AccountTreeItem* getParent();

	virtual const wchar_t* getDisplayName()
	{
		return AccountTreeItem::getDisplayName();

		//swprintf(_displayName, 1024, L"%s - $%.2f remaining in envelopes ($%.2f budgeted)", _name.c_str(), allocatedToSubAccounts(), budgetedToSubAccounts());
		//return _displayName;
	};

	// Get the IDs for this item and all child items. 
	virtual void getIdsForSelfAndChildren(std::set<unsigned int>& ids)
	{
		// Add self
		ids.insert(getId());

		// Add children
		for (size_t i = 0; i < _children.size(); i++) {
			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				pAccount->getIdsForSelfAndChildren(ids);
			}
		}
	}

	// Calculates the number of dollars budgeted to sub items
	virtual int budgetedToSubAccounts()
	{
		int budgeted = 0;
		for (size_t i = 0; i < _children.size(); i++)
		{
			budgeted += _children[i]->getBudgeted();

			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				budgeted += pAccount->budgetedToSubAccounts();

			}
		}
		return budgeted;
	}

	// Calculates the number of dollars allocated to sub items
	virtual int allocatedToSubAccounts()
	{
		int allocated = 0;
		for (size_t i = 0; i < _children.size(); i++)
		{
			AccountTreeItem* pCurChild = _children[i];
			allocated += pCurChild->getBalance();
			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				allocated += pAccount->allocatedToSubAccounts();
			}

		}
		return allocated;
	}

	// Add a child to this item
	virtual void addChild(AccountTreeItem* pChildAccount)
	{
		_children.push_back(pChildAccount);
	}

	virtual void addChild(AccountTreeItem* pItemToAdd, AccountTreeItem* pAddAfter)
	{
		for (auto itr = _children.begin(); itr != _children.end(); itr++)
		{
			if (*itr == pAddAfter)
			{
				itr++;
				_children.insert(itr, pItemToAdd);
				break;
			}
		}
	}


	virtual bool removeChild(AccountTreeItem* pChildAccount)
	{
		bool worked = false;
		for (auto itr = _children.begin(); itr != _children.end(); itr++)
		{
			if (*itr == pChildAccount) {
				worked = true;
				_children.erase(itr);
				break;
			}
		}
		return worked;
	}

	virtual bool isMyChild(unsigned int childId)
	{
		bool ret = false;
		for (size_t i = 0; i < _children.size(); i++)
		{
			if (_children[i]->getId() == childId || _children[i]->isMyChild(childId))
			{
				ret = true;
				break;
			}
		}
		return ret;
	}

	std::vector<AccountTreeItem*>& getChildren() { return _children; }


protected:
	wchar_t _displayName[1024];
	std::vector<AccountTreeItem*> _children;

};

// Account class and implementation
