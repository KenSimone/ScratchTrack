// Base class for items in the account tree
class AccountBase
{
public:
	enum accountItemType
	{
		ACCOUNT, // Holds funds
		GROUP, // Display-only method for dividing envelopes
		CATEGORY // A virtual account, essentially
	}; // enum accountItemType

	// Construction / destruction
	AccountBase(accountItemType type);
	virtual ~AccountBase() {};

	// The item-type (account/group/envelope)
	virtual accountItemType getType() = 0;
	static std::vector<AccountBase*> getAllAccountsOfType(accountItemType type);

	// Get parent item
	virtual AccountBase* getParent() { return nullptr; }

	// Each item in the tree has a unique ID throughout the system
	unsigned int getId() { return _id; }

	// Look up item by ID
	static AccountBase* lookupById(unsigned int id);

	// User-defined name for this item
	virtual const wchar_t* getName() { return _name.c_str(); }
	virtual void setName(const wchar_t* szName) { _name = szName; }

	// How many dollars an item has or is holding. Th is is a direct
	// value for accounts and envelopes, and is a calculated value for groups
	virtual int getBalance() { return _balance; }
	virtual void addBalance(int balance) { _balance += balance; }

	// The dollars budgeted to this item. This is a direct value for envelopes
	// and a calculated value for containers.
	virtual int getBudgeted() { return _budgeted; }
	virtual void setBudgeted(int budgeted) { _budgeted = budgeted; }

	// Transaction for self and sub accounts
	int getCurrentMonthTransacationTotal();

	virtual void addChild(AccountBase*) { };
	virtual void addChild(AccountBase*, AccountBase*) {}
	virtual bool removeChild(AccountBase*) { return false; }
	virtual void getIdsForSelfAndChildren(std::set<unsigned int>& ids)
	{
		ids.insert(getId());
	}

	virtual int budgetedToSubAccounts() { return 0; }
	virtual int allocatedToSubAccounts() { return 0; }

	virtual bool isMyChild(unsigned int childId) { return false; }


	// Subclasses should always call base first thing and then add to ppSerializedElement as needed
	virtual int serialize(tinyxml2::XMLElement* pParent, tinyxml2::XMLElement** ppSerializedElement);
	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);

protected:
	void setId(unsigned int id); // autogenerated at construction. Only call this at serialization

protected:
	std::wstring _name;
	int _balance;
	int _budgeted;
	unsigned int _id;
};

// Group / folder class and implementation
class AccountGroup : public AccountBase
{
public:
	AccountGroup() : AccountBase(GROUP), _displayName{ 0 } {};
	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);

	// The item-type (account/group/envelope)
	virtual accountItemType getType() { return AccountBase::GROUP; }

	// Groups only have aggregate balances from their children and hold no value on their own
	virtual int getBalance() { return 0; }
	virtual void addBalance(int balance) { _balance = 0; }

	virtual AccountBase* getParent();

	// Get the IDs for this item and all child items. 
	virtual void getIdsForSelfAndChildren(std::set<unsigned int>& ids)
	{
		// Add self
		ids.insert(getId());

		// Add children
		for (size_t i = 0; i < _children.size(); i++) {
			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				pAccount->getIdsForSelfAndChildren(ids);
			}
		}
	}

	// Calculates the number of dollars budgeted to sub items
	virtual int budgetedToSubAccounts()
	{
		int budgeted = 0;
		for (size_t i = 0; i < _children.size(); i++)
		{
			budgeted += _children[i]->getBudgeted();

			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				budgeted += pAccount->budgetedToSubAccounts();

			}
		}
		return budgeted;
	}

	// Calculates the number of dollars allocated to sub items
	virtual int allocatedToSubAccounts()
	{
		int allocated = 0;
		for (size_t i = 0; i < _children.size(); i++)
		{
			AccountBase* pCurChild = _children[i];
			allocated += pCurChild->getBalance();
			if (_children[i]->getType() == GROUP)
			{
				AccountGroup* pAccount = (AccountGroup*)_children[i];
				allocated += pAccount->allocatedToSubAccounts();
			}

		}
		return allocated;
	}

	// Add a child to this item
	virtual void addChild(AccountBase* pChildAccount)
	{
		_children.push_back(pChildAccount);
	}

	virtual void addChild(AccountBase* pItemToAdd, AccountBase* pAddAfter)
	{
		for (auto itr = _children.begin(); itr != _children.end(); itr++)
		{
			if (*itr == pAddAfter)
			{
				itr++;
				_children.insert(itr, pItemToAdd);
				break;
			}
		}
	}


	virtual bool removeChild(AccountBase* pChildAccount)
	{
		bool worked = false;
		for (auto itr = _children.begin(); itr != _children.end(); itr++)
		{
			if (*itr == pChildAccount) {
				worked = true;
				_children.erase(itr);
				break;
			}
		}
		return worked;
	}

	virtual bool isMyChild(unsigned int childId)
	{
		bool ret = false;
		for (size_t i = 0; i < _children.size(); i++)
		{
			if (_children[i]->getId() == childId || _children[i]->isMyChild(childId))
			{
				ret = true;
				break;
			}
		}
		return ret;
	}

	std::vector<AccountBase*>& getChildren() { return _children; }


protected:
	wchar_t _displayName[1024];
	std::vector<AccountBase*> _children;
};

// Account class and implementation
class Account : public AccountBase
{
public:
	Account() : AccountBase(ACCOUNT), _isBudgeted(true) {};
	bool isBudgeted() { return _isBudgeted;  }
	void setIsBudgeted(bool budgeted) { _isBudgeted = budgeted; }

	// The item-type (account/group/envelope)
	virtual accountItemType getType() { return AccountBase::ACCOUNT; }

	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);
	virtual int serialize(tinyxml2::XMLElement* pParent, tinyxml2::XMLElement** ppSerializedElement);

protected:
	bool _isBudgeted;

}; // class Account

// Envelope (category) class and implementation
class AccountCategory : public AccountBase
{
public:
	AccountCategory() : AccountBase(CATEGORY), _pDefaultTransactionPayFromAccount(nullptr), _defaultTransactionAmount(0), _isExpense(true), _isVirtualAccount(false) {};

	virtual accountItemType getType() { return AccountBase::CATEGORY; }

	// Transaction defaults
	int getDefaultTransactionAmount() { return _defaultTransactionAmount; }
	void setDefaultTransactionAmount(int iAmount) { _defaultTransactionAmount = iAmount; }
	const wchar_t* getDefaultTransactionPayee() { return _defaultTransactionPayee.c_str(); }
	void setDefaultTransactionPayee(const wchar_t* szPayee) { _defaultTransactionPayee = szPayee; }
	Account* getDefaultTransactionPayFromAccount() { return _pDefaultTransactionPayFromAccount; }
	void setDefaultTransactionPayFromAccount(Account* pAccount) { _pDefaultTransactionPayFromAccount = pAccount; }

	bool isExpense() { return _isExpense; }
	bool isVirtualAccount() { return _isVirtualAccount; }

	void setIsExpense(bool isExpense) { _isExpense = isExpense; }
	void setIsVirtualAccount(bool isVirtualAccount) { _isVirtualAccount = isVirtualAccount; }

	virtual int initItemFromXmlElement(tinyxml2::XMLElement* pAccount);
	virtual int serialize(tinyxml2::XMLElement* pParent, tinyxml2::XMLElement** ppSerializedElement);

protected:
	std::wstring _defaultTransactionPayee;
	Account* _pDefaultTransactionPayFromAccount;
	int _defaultTransactionAmount;
	bool _isExpense;
	bool _isVirtualAccount;
}; // class Envelope
